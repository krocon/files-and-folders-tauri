#!/usr/bin/env node
// Licence report of the dependencies (design 017 E7) – no extra tools needed:
// npm via `pnpm licenses list --json`, Rust via `cargo metadata` (all target platforms,
// so Windows/macOS-only crates are included). Writes Markdown to stdout.
//
//   node scripts/licenses.mjs > docs/licenses.md
//
// Our own licence is still open (CLAUDE.md §8) – this report does not set it.
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

/** Licences that need no action for a binary distribution beyond attribution. */
const PERMISSIVE = new Set([
  'MIT',
  'Apache-2.0',
  'Apache-2.0 WITH LLVM-exception',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'ISC',
  'Zlib',
  '0BSD',
  'CC0-1.0',
  'Unicode-3.0',
  'Unicode-DFS-2016',
  'Unlicense',
  'BSL-1.0',
  'MIT-0',
  'CDLA-Permissive-2.0',
]);

/** True if one alternative of an SPDX expression (OR, AND inside) is fully permissive. */
export function isPermissive(expr) {
  if (!expr) return false;
  const norm = expr.replace(/\//g, ' OR ').replace(/[()]/g, ' ');
  return norm
    .split(/\s+OR\s+/)
    .some((alt) => alt.split(/\s+AND\s+/).every((l) => PERMISSIVE.has(l.trim())));
}

export function summarise(packages) {
  const by = new Map();
  for (const p of packages) {
    const key = p.license || '(none)';
    by.set(key, (by.get(key) ?? 0) + 1);
  }
  return [...by.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
}

function npmPackages(prod) {
  const out = execFileSync('pnpm', ['licenses', 'list', '--json', ...(prod ? ['--prod'] : [])], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    shell: process.platform === 'win32',
  });
  const data = JSON.parse(out);
  return Object.entries(data).flatMap(([license, list]) =>
    list.map((p) => ({ name: p.name, version: p.versions.join(', '), license })),
  );
}

function cargoPackages() {
  const out = execFileSync(
    'cargo',
    ['metadata', '--format-version', '1', '--manifest-path', 'src-tauri/Cargo.toml', '--locked'],
    { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 },
  );
  const meta = JSON.parse(out);
  const own = new Set(meta.workspace_members);
  return meta.packages
    .filter((p) => !own.has(p.id))
    .map((p) => ({
      name: p.name,
      version: p.version,
      license: p.license ?? (p.license_file ? `file: ${p.license_file}` : null),
    }));
}

function section(title, packages) {
  const lines = [`## ${title}`, '', `${packages.length} packages.`, '', '| Licence | Count |', '|---|---|'];
  for (const [l, n] of summarise(packages)) lines.push(`| ${l} | ${n} |`);
  const flagged = packages.filter((p) => !isPermissive(p.license));
  lines.push('', '**Needs a look (not purely permissive):**', '');
  if (flagged.length === 0) lines.push('- none');
  for (const p of flagged.sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`- \`${p.name}\` ${p.version} – ${p.license ?? '(no licence field)'}`);
  }
  lines.push('');
  return lines;
}

/**
 * Source code compiled into the app whose licence the crate's own licence field does not
 * show (design 025 E2). The UnRAR licence asks for its paragraph 2 in the documentation.
 */
const BUNDLED_SOURCE = [
  '## Bundled source with its own licence',
  '',
  '- `unrar-ng-sys` (MIT OR Apache-2.0) compiles the vendored **UnRAR** C++ source (RAR',
  '  read/extract only, Cargo feature `rar`, on by default). UnRAR licence, paragraph 2:',
  '',
  '  > UnRAR source code may be used in any software to handle RAR archives without',
  '  > limitations free of charge, but cannot be used to develop RAR (WinRAR) compatible',
  '  > archiver and to re-create RAR compression algorithm, which is proprietary.',
  '  > Distribution of modified UnRAR source code in separate form or as a part of other',
  '  > software is permitted, provided that full text of this paragraph, starting from',
  '  > "UnRAR source code" words, is included in license, or in documentation if license',
  '  > is not available, and in source code comments of resulting package.',
  '',
  '  All copyrights to RAR and UnRAR are owned by Alexander Roshal. Files and Folders never',
  '  creates RAR archives. Build without it: `cargo build --no-default-features`.',
  '',
];

function main() {
  const npmProd = npmPackages(true);
  const npmAll = npmPackages(false);
  const cargo = cargoPackages();
  const md = [
    '# Licences of the dependencies',
    '',
    '> Generated by `pnpm licenses:report` (`scripts/licenses.mjs`). Rust: every crate in',
    '> `Cargo.lock` for all target platforms (incl. build and dev dependencies, so this is an',
    '> upper bound). npm: runtime dependencies shipped in the bundle; dev tooling only as a summary.',
    '> The licence of Files and Folders itself is still open (CLAUDE.md §8).',
    '',
    ...section('Rust crates (Cargo.lock)', cargo),
    ...section('npm – runtime (in the app bundle)', npmProd),
    ...BUNDLED_SOURCE,
    `## npm – development tooling (not shipped)`,
    '',
    `${npmAll.length} packages; not purely permissive: ${npmAll.filter((p) => !isPermissive(p.license)).length}`,
    '(build tools only, not part of the distributed app).',
    '',
  ];
  process.stdout.write(md.join('\n'));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
